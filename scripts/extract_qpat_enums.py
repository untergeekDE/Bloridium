"""Extract enum value->display histograms from .qpat files (offline, no MIDI).

Scans files / directories / .zip archives, groups the result by qpat version and
collects, for every parameter whose name starts with one of --prefixes, a
histogram of (value -> display) across all patches. Parameter names are also
aggregated by stem (trailing digits stripped, e.g. MatrixSrc1..40 -> MatrixSrc),
so enum tables can be read off directly.

Use it to verify/derive enum tables (MatrixSrc/MatrixDst, FX types, ...) per
qpat version, e.g. to see the v8 vs v14 vs v15 enum shifts:

    python3 scripts/extract_qpat_enums.py dumps/export-001 dumps/export-003 \
        docs/refs/Quantum_Factories.zip \
        --prefix MatrixSrc MatrixDst AfterTouchDoPoly FX1Type FX2Type \
        --out docs/refs/qpat_enum_scan.json --md docs/refs/qpat_enum_scan.md
"""

from __future__ import annotations

import argparse
import json
import re
import sys
import zipfile
from collections import Counter, defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from bloridium import qpat  # noqa: E402


def iter_qpat_bytes(paths):
    """Yield (source_label, data) for every .qpat under the given files/dirs/zips."""
    for raw in paths:
        p = Path(raw)
        if p.is_dir():
            for f in sorted(p.rglob("*.qpat")):
                yield str(f), f.read_bytes()
        elif p.suffix.lower() == ".zip":
            with zipfile.ZipFile(p) as z:
                for name in sorted(z.namelist()):
                    if name.lower().endswith(".qpat"):
                        yield f"{p.name}::{name}", z.read(name)
        elif p.suffix.lower() == ".qpat":
            yield str(p), p.read_bytes()


def stem(name: str) -> str:
    return re.sub(r"\d+$", "", name)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("paths", nargs="+", help=".qpat files, dirs or .zip archives")
    ap.add_argument("--prefix", action="append", nargs="+", default=[],
                    help="param-name prefix(es) to collect, e.g. --prefix MatrixSrc MatrixDst")
    ap.add_argument("--out", help="write JSON result here")
    ap.add_argument("--md", help="write a markdown table here")
    args = ap.parse_args()
    prefixes = tuple(p for group in args.prefix for p in group) or ("MatrixSrc", "MatrixDst")

    # version -> stem -> value -> {display: count}; plus per-param detail
    by_version = defaultdict(lambda: defaultdict(lambda: defaultdict(Counter)))
    per_param = defaultdict(lambda: defaultdict(lambda: defaultdict(Counter)))
    n_files = 0
    for src, data in iter_qpat_bytes(args.paths):
        try:
            q = qpat.parse_qpat(data)
        except Exception:
            continue
        n_files += 1
        ver = q.get("version", "?")
        for name, rec in q["params"].items():
            if not name.startswith(prefixes):
                continue
            val = round(float(rec["value"]), 6)
            disp = rec.get("display", "")
            by_version[ver][stem(name)][val][disp] += 1
            per_param[ver][name][val][disp] += 1

    result = {
        "files": n_files,
        "prefixes": list(prefixes),
        "by_stem": {str(v): {s: {str(val): dict(c) for val, c in d.items()}
                             for s, d in stems.items()}
                    for v, stems in sorted(by_version.items(), key=lambda kv: str(kv[0]))},
        "per_param": {str(v): {n: {str(val): dict(c) for val, c in d.items()}
                               for n, d in params.items()}
                      for v, params in sorted(per_param.items(), key=lambda kv: str(kv[0]))},
    }
    if args.out:
        Path(args.out).write_text(json.dumps(result, indent=1, ensure_ascii=False))
        print(f"JSON -> {args.out}")
    if args.md:
        lines = [f"# qpat enum scan ({n_files} files)", "",
                 "value -> display histograms per qpat version, aggregated by param stem.",
                 "Generated by `scripts/extract_qpat_enums.py`.", ""]
        for ver in sorted(result["by_stem"], key=str):
            lines.append(f"## version {ver}")
            for s in sorted(result["by_stem"][ver]):
                lines.append(f"\n### `{s}`")
                lines.append("\n| value | display (count) |")
                lines.append("|---|---|")
                for val in sorted(result["by_stem"][ver][s], key=float):
                    disps = "; ".join(f"{d!r} x{c}" for d, c in
                                      sorted(result["by_stem"][ver][s][val].items(),
                                             key=lambda kv: -kv[1]))
                    lines.append(f"| {val} | {disps} |")
            lines.append("")
        Path(args.md).write_text("\n".join(lines))
        print(f"MD   -> {args.md}")
    print(f"scanned {n_files} qpat files, versions: "
          + ", ".join(f"v{v} x{sum(len(p) for p in per_param[v].values())} params"
                      for v in sorted(per_param, key=str)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
